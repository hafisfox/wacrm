import crypto from 'node:crypto';
import fs from 'node:fs';
import { loadEnvFile, shellQuote } from './env-utils.mjs';

const rootEnv = loadEnvFile(new URL('../../.env', import.meta.url));
const existing = loadEnvFile(new URL('../.env.local', import.meta.url));

function first(...values) {
  return values.find((value) => String(value || '').trim()) || '';
}

function encryptionKey() {
  const current = first(existing.ENCRYPTION_KEY, rootEnv.ENCRYPTION_KEY);
  if (/^[a-f0-9]{64}$/i.test(current)) return current;
  return crypto.randomBytes(32).toString('hex');
}

const values = {
  NEXT_PUBLIC_SUPABASE_URL: first(
    existing.NEXT_PUBLIC_SUPABASE_URL,
    rootEnv.NEXT_PUBLIC_SUPABASE_URL,
    rootEnv.SUPABASE_URL,
  ),
  NEXT_PUBLIC_SUPABASE_ANON_KEY: first(
    existing.NEXT_PUBLIC_SUPABASE_ANON_KEY,
    rootEnv.NEXT_PUBLIC_SUPABASE_ANON_KEY,
    rootEnv.SUPABASE_ANON_KEY,
    rootEnv.SUPABASE_PUBLISHABLE_KEY,
  ),
  SUPABASE_SERVICE_ROLE_KEY: first(
    existing.SUPABASE_SERVICE_ROLE_KEY,
    rootEnv.SUPABASE_SERVICE_ROLE_KEY,
  ),
  SALU_BOOKING_DATABASE_URL: first(
    existing.SALU_BOOKING_DATABASE_URL,
    rootEnv.SALU_BOOKING_DATABASE_URL,
    rootEnv.DATABASE_URL,
  ),
  DATABASE_URL: first(
    existing.DATABASE_URL,
    rootEnv.SALU_BOOKING_DATABASE_URL,
    rootEnv.DATABASE_URL,
  ),
  N8N_URL: first(existing.N8N_URL, rootEnv.N8N_URL),
  N8N_API_KEY: first(existing.N8N_API_KEY, rootEnv.N8N_API_KEY),
  SALU_N8N_MANUAL_SEND_TOKEN: first(
    existing.SALU_N8N_MANUAL_SEND_TOKEN,
    rootEnv.SALU_N8N_MANUAL_SEND_TOKEN,
  ),
  NEXT_PUBLIC_SITE_URL: first(existing.NEXT_PUBLIC_SITE_URL, 'http://localhost:3000'),
  ENCRYPTION_KEY: encryptionKey(),
  META_APP_SECRET: first(
    existing.META_APP_SECRET,
    rootEnv.META_APP_SECRET,
    'n8n-owns-salu-whatsapp-webhook',
  ),
  SALU_DASHBOARD_MODE: 'n8n-owned-whatsapp',
};

const missing = [
  'NEXT_PUBLIC_SUPABASE_URL',
  'NEXT_PUBLIC_SUPABASE_ANON_KEY',
  'SUPABASE_SERVICE_ROLE_KEY',
  'SALU_BOOKING_DATABASE_URL',
].filter((key) => !values[key]);

if (missing.length) {
  throw new Error(`Missing required Salu dashboard env values: ${missing.join(', ')}`);
}

const lines = [
  '# Generated by npm run setup:salu-env.',
  '# n8n remains the production WhatsApp webhook owner for Salu.',
  '',
  ...Object.entries(values).map(([key, value]) => `${key}=${shellQuote(value)}`),
  '',
];

const target = new URL('../.env.local', import.meta.url);
fs.writeFileSync(target, lines.join('\n'), { mode: 0o600 });
console.log(JSON.stringify({ ok: true, wrote: '.env.local', mode: values.SALU_DASHBOARD_MODE }));
